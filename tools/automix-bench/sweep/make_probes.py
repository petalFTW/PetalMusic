"""Generate test-only probe copies of DjComposer and TrackAnalyzer (no engine change).
Usage: python make_probes.py <repo root>"""
import sys, pathlib
root = pathlib.Path(sys.argv[1])
src = root / "app/src/main/kotlin/org/rab1d/petal/music/playback"
dst = root / "app/src/test/kotlin/org/rab1d/petal/music/probe"
dst.mkdir(parents=True, exist_ok=True)

def patch(text, old, new, count=1):
    assert text.count(old) == count, (old, text.count(old))
    return text.replace(old, new)

HEADER = "// GENERATED by tools/automix-bench/sweep/make_probes.py from main sources. Test-only probe; do not edit.\n"

c = (src / "DjComposer.kt").read_text(encoding="utf-8")
c = patch(c, "object DjComposer {", """object DjComposerProbe {
    /** Probe knobs (per thread): force one family, scale jitter, disable variety. */
    val force = ThreadLocal<Family?>()
    val jitterScale: ThreadLocal<Double> = ThreadLocal.withInitial { 1.0 }
    val variety: ThreadLocal<Boolean> = ThreadLocal.withInitial { true }
    val lastCandidates = ThreadLocal<List<Triple<Family, Double, Int>>>()
""")
for name in ["MIN_CONFIDENCE", "MAX_STRETCH", "OVERLAY_STRETCH"]:
    c = patch(c, f"private const val {name} =", f"@JvmField var {name} =")
c = patch(c, "            if (clean && family !in CLEAN_FAMILIES) continue\n",
          "            if (clean && family !in CLEAN_FAMILIES) continue\n            if (force.get() != null && family != force.get()) continue\n")
c = patch(c, "        // A beat-matched pair blends whenever any blend fits; cuts are for pairs that cannot.\n",
          "        lastCandidates.set(candidates.map { Triple(it.family, it.score, it.length) })\n        // A beat-matched pair blends whenever any blend fits; cuts are for pairs that cannot.\n")
c = patch(c, "\"candidates=${candidates.size}\"",
          "\"candidates=${candidates.size} exitStyle=${best.exitStyle} entry=${best.entry} exit=${best.exit} kill=${best.killOutgoingLow}\"")
c = patch(c, "total += jitter(family.ordinal) * if (clean)", "total += jitterScale.get()!! * jitter(family.ordinal) * if (clean)")
c = patch(c, "if (!clean || !family.blend) {", "if (variety.get()!! && (!clean || !family.blend)) {")
(dst / "DjComposerProbe.kt").write_text(HEADER + c, encoding="utf-8")

t = (src / "TrackAnalyzer.kt").read_text(encoding="utf-8")
t = patch(t, "internal object TrackAnalyzer {", "internal object TrackAnalyzerProbe {\n    /** Last grid() breakdown on this thread. */\n    val diag = ThreadLocal<String>()")
t = patch(t, "        var agree = 0\n", "        val segLog = StringBuilder()\n        var agree = 0\n")
t = patch(t, "            if (abs(segPhase) * s.hopMs <= 15) agree += 2\n",
          "            segLog.append(\"%.0f/%.2f \".format(segPhase * s.hopMs, support(bp, bphi, from, to) / segBest.coerceAtLeast(1e-9)))\n            if (abs(segPhase) * s.hopMs <= 15) agree += 2\n")
t = patch(t, "        // Every segment agreeing is the strongest evidence of a quantised grid.\n",
          "        diag.set(\"z=%.2f stand=%.2f agree=%d/%d segs=%s\".format(z, stand, agree, 2 * valid, segLog.toString().trim()))\n        // Every segment agreeing is the strongest evidence of a quantised grid.\n")
(dst / "TrackAnalyzerProbe.kt").write_text(HEADER + t, encoding="utf-8")
print("ok")
